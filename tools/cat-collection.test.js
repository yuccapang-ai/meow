'use strict';
var assert = require('assert');
var Collection = require('../app/js/cat-collection.js');
var Engine = require('../app/js/engine.js');
var values = {}, storage = { getItem: function (key) { return values[key] || null; }, setItem: function (key, value) { values[key] = value; } };
var collection = Collection.create(storage);
assert.strictEqual(collection.list().length, 18);
assert.strictEqual(collection.list('cats').length, 9);
assert.strictEqual(collection.list('tortie').length, 9);
assert.deepStrictEqual(collection.list().filter(function (p) { return p.home; }).map(function (p) { return p.cat.id; }), ['donut', 'tortie-strawberry']);
assert.strictEqual(collection.progress('donut').special, false);
assert.strictEqual(collection.progress('missing'), null);

collection.recordRun('cats', [29,29,0,0,0,0,0,0,0], 'first');
assert.strictEqual(collection.progress('coder').home, false);
var milestones = collection.recordRun('cats', [1,1,0,0,0,0,0,0,0], 'second');
assert.deepStrictEqual(milestones.map(function (m) { return m.id + ':' + m.kind; }), ['coder:body']);
assert.strictEqual(collection.progress('coder').body, true);
assert.strictEqual(collection.progress('coder').home, false);
assert.strictEqual(collection.progress('coder').special, false);
collection.recordRun('cats', [19,19], 'third');
assert.strictEqual(collection.progress('donut').special, false);
assert.strictEqual(collection.progress('coder').special, false);
milestones = collection.recordRun('cats', [1,1], 'fourth');
assert.deepStrictEqual(milestones.map(function (m) { return m.id + ':' + m.kind; }), ['donut:special','coder:home','coder:special']);
assert.strictEqual(collection.progress('coder').home, true);
assert.strictEqual(collection.progress('donut').count, 50);
collection.recordRun('cats', [100,100], 'fourth');
collection.recordRun('cats', [100,100], 'replay', true);
assert.strictEqual(collection.progress('donut').count, 50, 'duplicate settlement and replays cannot add cats');

// Different skins share color indices but represent different cats.
collection.recordRun('pengci', [100,100,100,100,100,100,100,100,100], 'other-skin');
assert.strictEqual(collection.progress('music').count, 0);
assert.strictEqual(collection.progress('donut').count, 50);
var restored = Collection.create(storage);
assert.strictEqual(restored.progress('coder').special, true);
assert.strictEqual(restored.progress('donut').count, 50);
assert.strictEqual(restored.progress('music').home, false);

// All nine amounts from the engine are added, including cats remaining on board.
var run = Engine.startRun({}, Engine.seededRandom(17));
run.stash = [1,2,3,4,5,6,7,8,9]; run.board = [0,1,2,3,4,5,6,7,8];
var tally = Engine.tally(run), before = restored.list('cats').map(function (p) { return p.count; });
restored.recordRun('cats', tally.counts, 'engine-result');
restored.list('cats').forEach(function (p, i) { assert.strictEqual(p.count - before[i], tally.counts[i]); });
assert.strictEqual(restored.list('cats').reduce(function (sum, p, i) { return sum + p.count - before[i]; }, 0), tally.total);
assert.ok(restored.list('tortie').every(function (entry) { return entry.count === 0; }));

var jump = Collection.create(null);
milestones = jump.recordRun('cats', [0,0,100], 'jump');
assert.deepStrictEqual(milestones.map(function (m) { return m.kind; }), ['body','special']);
assert.strictEqual(jump.progress('music').special, true, 'storage unavailable still keeps session progress');
milestones = jump.recordRun('cats', [0,0,100], 'second-jump');
assert.deepStrictEqual(milestones.map(function (m) { return m.kind; }), ['home']);
assert.doesNotThrow(function () { jump.recordRun('constructor', [5], 'weird-skin'); });
var corrupt = Collection.create({ getItem: function () { return '{bad json'; } });
assert.strictEqual(corrupt.progress('donut').home, true);
var invalid = Collection.create({ getItem: function () { return JSON.stringify({ version: 1, counts: { cats: [-5,'100',null,1e20,50.9] } }); } });
assert.deepStrictEqual(invalid.list().slice(0,5).map(function (p) { return p.count; }), [0,0,0,1000000000,50]);
var oldSave = Collection.create({ getItem: function () { return JSON.stringify({ version: 1, counts: { cats: [50,30,49,50] } }); } });
assert.strictEqual(oldSave.progress('coder').home, true);
assert.strictEqual(oldSave.progress('coder').special, false);
assert.strictEqual(oldSave.progress('music').special, false);
assert.strictEqual(oldSave.progress('coffee').special, true);
assert.strictEqual(oldSave.progress('tortie-strawberry').home, true);
assert.strictEqual(oldSave.progress('tortie-sailor').count, 0);
var tortie = Collection.create(storage), legacyCounts = tortie.list('cats').map(function (entry) { return entry.count; });
tortie.recordRun('tortie', [0,29], 'tortie-29');
assert.strictEqual(tortie.progress('tortie-sailor').body, false);
tortie.recordRun('tortie', [0,1], 'tortie-30');
assert.strictEqual(tortie.progress('tortie-sailor').body, true);
assert.strictEqual(tortie.progress('tortie-sailor').home, false);
tortie.recordRun('tortie', [0,19], 'tortie-49');
assert.strictEqual(tortie.progress('tortie-sailor').special, false);
tortie.recordRun('tortie', [0,1], 'tortie-50');
assert.strictEqual(tortie.progress('tortie-sailor').special, true);
assert.strictEqual(tortie.progress('tortie-sailor').home, false);
tortie.recordRun('tortie', [49], 'tortie-99');
assert.strictEqual(tortie.progress('tortie-sailor').home, false);
tortie.recordRun('tortie', [1], 'tortie-100');
assert.strictEqual(tortie.progress('tortie-sailor').home, true);
assert.deepStrictEqual(tortie.list('cats').map(function (entry) { return entry.count; }), legacyCounts);
assert.strictEqual(Collection.create(storage).progress('tortie-sailor').count, 50);
tortie.recordRun('tortie', [100,100], 'tortie-100');
tortie.recordRun('tortie', [100,100], 'tortie-replay', true);
assert.strictEqual(tortie.progress('tortie-sailor').count, 50);
Collection.series.forEach(function (series) {
  collection.list(series.id).forEach(function (entry, index) {
    assert.strictEqual(entry.cat.bodyAt, index ? 30 : 0);
    assert.strictEqual(entry.cat.homeAt, index * 100);
    assert.strictEqual(entry.cat.specialAt, 50);
  });
});
console.log('PASS: two independent series, matching 30/100/50 boundaries, starter cats, old saves, persistence, engine counts and replay guards.');
